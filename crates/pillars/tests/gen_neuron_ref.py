#!/usr/bin/env python3
"""Generate NEURON reference data for LIF and AdEx models used by pillars tests.

Usage: python3 gen_neuron_ref.py

Output: prints Rust assert statements with NEURON reference values.
"""

import neuron
h = neuron.h

def gen_lif_ref():
    """LIF reference using NEURON IntFire1 (integrate-and-fire with refractory)."""
    h.dt = 0.025
    
    for i_nA, label in [(0.05, "I50"), (0.1, "I100"), (0.2, "I200")]:
        cell = h.IntFire1(0, 0, 0)  # soma
        cell.tau = 10.0      # ms (LIF tau_m)
        cell.refractory = 2.0  # ms tau_ref
        cell.v = -70.0       # reset
        cell.thresh = -54.0  # threshold
        
        stim = h.IClamp(0.5, sec=cell)
        stim.delay = 10.0
        stim.dur = 90.0
        stim.amp = i_nA
        
        nc = h.NetCon(cell, None)
        nc.threshold = -54.0
        
        spikes = []
        def record_spike():
            spikes.append(h.t)
        nc = h.NetCon(cell, None)
        _ = nc.record(lambda: spikes.append(h.t))
        
        h.finitialize(-70.0)
        h.run()
        
        total_spikes = len(spikes)
        print(f"    // LIF {label}: NEURON IntFire1, I={i_nA}nA, tau=10, refr=2")
        print(f"    // {{label: \"{label}\", i_nA: {i_nA}, ref_spikes: {total_spikes}}},")


