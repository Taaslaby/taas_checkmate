//! NEURON parity for the Markov (kinetic-scheme) engine.
//!
//! Validates `MarkovPopulation` (scalar master-equation integrator, exact
//! matrix exponential) against NEURON `KINETIC` schemes:
//!
//! * `ks2.mod` — 2-state closed ⇌ open, rates = Na-m gate (`na_m_alpha` /
//!   `na_m_beta`);
//! * `ks3.mod` — 3-state closed ⇌ open ⇌ inactivated, rates = Na-m + Na-h
//!   (open state is the middle one).
//!
//! Both are inserted as K-like channels (E_rev = -77 mV) next to a passive
//! leak and driven by the same subthreshold current-clamp protocol
//! (dt = 0.025 ms, 100 ms, I = +10 µA/cm² from t=10 to 60 ms, V0 = -65 mV).
//!
//! The references `REF_V_KS2` / `REF_V_KS3` are V(t) sampled every 5 ms,
//! generated by `resources/validate/neuron_models/gen_ks_ref.py`
//! (NEURON 9.0.2, fixed-step, `KINETIC` solved with `METHOD sparse`).
//! NEURON uses Crank-Nicolson for the membrane + backward Euler for the
//! kinetic scheme, pillars uses implicit Euler (derivimplicit) for the
//! membrane + the *exact* matrix exponential for the master equation — so
//! agreement is to integrator accuracy (≲6e-4 mV), not bit-exact.

use pillars::api::{MarkovChannel, MarkovPopulation, Population};
use pillars::kernels::hh_channels::{ClosedForm, MarkovGateSpec, MarkovRate, MarkovTransition};

const DT: f32 = 0.025;
const T_MS: f32 = 100.0;
const V0: f32 = -65.0;
const I_AMP: f32 = 10.0; // µA/cm²
const PULSE_ON_MS: f32 = 10.0;
const PULSE_OFF_MS: f32 = 60.0;
const G_LEAK: f32 = 0.3;
const E_LEAK: f32 = -54.3;
const CM: f32 = 1.0;
const G_CH: f32 = 36.0;
const E_REV: f32 = -77.0;
const CELSIUS: f32 = 6.3; // Q10 = 1

/// NEURON reference V(t) for the 2-state scheme, every 5 ms (t = 0, 5, …, 100).
