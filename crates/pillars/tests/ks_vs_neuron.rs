/// 2-state gate (closed ⇌ open), rates = Na-m α/β.
fn ks2_gate() -> MarkovGateSpec {
    MarkovGateSpec {
        open: vec![0.0, 1.0],
        transitions: vec![
            MarkovTransition {
                from: 0,
                to: 1,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::ExpLinear {
                        rate: 0.1,
                        midpoint: 40.0,
                        scale: 10.0,
                    },
                },
            },
            MarkovTransition {
                from: 1,
                to: 0,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::Exp {
                        rate: 4.0,
                        midpoint: 65.0,
                        scale: 18.0,
                    },
                },
            },
        ],
        power: 1,
    }
}

/// 3-state gate (closed ⇌ open ⇌ inactivated), rates = Na-m (0↔1) + Na-h (1↔2).
fn ks3_gate() -> MarkovGateSpec {
    MarkovGateSpec {
        open: vec![0.0, 1.0, 0.0],
        transitions: vec![
            MarkovTransition {
                from: 0,
                to: 1,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::ExpLinear {
                        rate: 0.1,
                        midpoint: 40.0,
                        scale: 10.0,
                    },
                },
            },
            MarkovTransition {
                from: 1,
                to: 0,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::Exp {
                        rate: 4.0,
                        midpoint: 65.0,
                        scale: 18.0,
                    },
                },
            },
            MarkovTransition {
                from: 1,
                to: 2,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::Exp {
                        rate: 0.07,
                        midpoint: 65.0,
                        scale: 20.0,
                    },
                },
            },
            MarkovTransition {
                from: 2,
                to: 1,
                rate: MarkovRate::Directed {
                    rate: ClosedForm::Sigmoid {
                        rate: 1.0,
                        midpoint: 35.0,
                        scale: 10.0,
                    },
                },
            },
        ],
        power: 1,
    }
}

fn build_pop(gate: MarkovGateSpec) -> MarkovPopulation {
    let channels = vec![MarkovChannel {
        gates: vec![gate],
        e_rev: E_REV,
        g_max: G_CH,
    }];
    let mut pop = MarkovPopulation::new(channels, 1, DT, CELSIUS);
    pop.set_cm(CM);
    pop.set_leak(G_LEAK, E_LEAK);
    pop.set_g_max(0, G_CH);
    pop.set_resting_state(V0);
    pop
}

/// Run the shared protocol, return V(t) for t = 0, DT, …, T_MS.
fn run_trace(pop: &mut MarkovPopulation) -> Vec<f32> {
    let n_steps = (T_MS / DT) as usize;
    let on = (PULSE_ON_MS / DT) as usize;
    let off = (PULSE_OFF_MS / DT) as usize;
    let mut i_in = [0.0f32; 1];
    let mut spikes = [0i32; 1];
    let mut v_trace = Vec::with_capacity(n_steps + 1);
    v_trace.push(pop.state_slice(0)[0]); // t = 0, before the first step
    for step in 0..n_steps {
        i_in[0] = if step >= on && step < off { I_AMP } else { 0.0 };
        pop.step(&i_in, &mut spikes);
        v_trace.push(pop.state_slice(0)[0]);
    }
    v_trace
}

/// Compare a pillars trace against a NEURON reference sampled every 5 ms.
/// Returns the max |ΔV|.
fn max_diff(v_trace: &[f32], ref_v: &[f32; 21]) -> f32 {
    let grid = (5.0 / DT) as usize;
    let mut max = 0.0f32;
    for (k, &ref_v) in ref_v.iter().enumerate() {
        max = max.max((v_trace[k * grid] - ref_v).abs());
    }
    max
}

#[test]
fn ks2_channel_matches_neuron() {
    let mut pop = build_pop(ks2_gate());
    let v_trace = run_trace(&mut pop);
    let d = max_diff(&v_trace, &REF_V_KS2);
    println!("ks2 vs NEURON: max |ΔV| = {d:.6} mV");
    assert!(d < 0.05, "ks2 vs NEURON: max |ΔV| = {d:.4} mV");
}

#[test]
fn ks3_channel_matches_neuron() {
    let mut pop = build_pop(ks3_gate());
    let v_trace = run_trace(&mut pop);
    let d = max_diff(&v_trace, &REF_V_KS3);
    println!("ks3 vs NEURON: max |ΔV| = {d:.6} mV");
    assert!(d < 0.05, "ks3 vs NEURON: max |ΔV| = {d:.4} mV");
}
