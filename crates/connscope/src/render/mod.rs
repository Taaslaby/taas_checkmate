//! # Отрисовка коннектома (`render`)
//!
//! Три пути визуализации, от дешёвого к дорогому:
//!
//! * [`atlas`] — программная запечка 2D/3D в `ColorImage`-текстуру
//!   (проекции XY/XZ/YZ, heatmap-трасса первого спайка);
//! * [`lod`] — уровни детализации облака точек (Potree-стиль: представители
//!   ячеек сетки на дальнем плане);
//! * [`splat`] — GPU-рендер на wgpu: биллборд-квады + объёмные сферы,
//!   CPU-сортировка по глубине, освещение (diffuse/Phong/rim), живое свечение
//!   потоковой симуляции.
//!
//! Общая конвенция: координаты мира нормализованы в `[0,1]³`, проекция
//! камеры — `yaw` (вокруг Z) + `pitch` (вокруг X) + перспектива, как в
//! [`atlas::project3d`].

pub(crate) mod atlas;
pub(crate) mod lod;
pub(crate) mod splat;
