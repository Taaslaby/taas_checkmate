#!/usr/bin/env python3
"""Generate the NEURON reference for the FULL Poirazi 2003 CA1 pyramidal cell
(dendritic tree, 5160 morphology segments) from the published NeuroML2 export.

Mirrors the pillars engine's d_λ discretization **exactly** (same CableParams:
Ra = 50 Ω·cm from `0.05kohm_cm`, Cm = 1 µF/cm², Rm = 1/first-leak, d_lambda =
0.1), builds one NEURON section per engine compartment (branch nodes become
shared connection points), inserts the 21 generated channel mechanisms per
segmentGroup (uniform, non-uniform `PathLength*` and GHK2 densities), the
Poirazi `capool` on the Ca species groups, and runs the published protocols.

Prints V(soma) on a 5 ms grid + spike counts + soma [Ca²⁺]; values are
hardcoded into the Rust regression (NEURON is not available in CI).

Usage: gen_poirazi_full_ref.py <cell_dir> <out_dir> <celsius>
"""
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
NEURON_HOME = r"C:\nrn"
MKNrndll = os.path.join(NEURON_HOME, "bin", "mknrndll.bat")

DT = 0.025
V0 = -70.0
THRESH = 0.0
D_LAMBDA = 0.1
CM = 1.0

# Published protocols: (name, I nA, on ms, off ms, tstop ms).
PROTOCOLS = [
    ("depolarizing_spikes", +1.0e-6, 50.0, 100.0, 150.0),
    ("hyperpolarizing_ih", -1.0e-7, 50.0, 100.0, 150.0),
]

# All channel mechanisms the cell references (generated by gen_poirazi_mods.py)
# plus the Ca pool.
MODS = [
    "cagk", "cal", "calH", "car", "cardend", "cat", "hs", "hdend", "kadist",
    "kaprox", "kca", "kdr", "kdrdend", "km", "leak_chan", "na",
    "nadend_1", "nadend_0_95", "nadend_0_4335", "nadend_0_3", "nap",
    "capool",
]

# GHK (channelDensityGHK2) channels — their mods carry USEION ca and the
# h2 = ki/(ki+cai) blocking factor.
GHK_CHANNELS = {"cal", "cat"}

# capool parameters (from channels/capool.nml).
CAPOOL_DEPTH_NM = 100.0   # 0.1 um shell thickness
CAPOOL_TAU_MS = 200.0     # decayConstant
CAPOOL_CAI0 = 1e-4        # restingConc (mM)


def local(tag):
    """Strip the XML namespace from a tag name."""
    return tag.rsplit("}", 1)[-1]


def attr(el, name, default=None):
    v = el.get(name)
    return v if v is not None else default


def parse_num_unit(s):
    """'5e-3mS_per_cm2' -> (5e-3, 'mS_per_cm2'); bare number -> (n, '')."""
    m = re.match(r"^\s*([+-]?[0-9.eE+-]+)\s*([A-Za-z_/0-9]*)\s*$", s)
    if not m:
        return float(s), ""
    return float(m.group(1)), m.group(2)


def cond_to_s_per_cm2(s):
    """NeuroML condDensity -> S/cm² (the mod's gbar unit)."""
    val, unit = parse_num_unit(s)
    if unit in ("", "S_per_cm2"):
        return val
    if unit == "mS_per_cm2":
        return val * 1e-3
    if unit == "S_per_m2":
        return val * 1e-4
    if unit == "mS_per_m2":
        return val * 1e-7
    raise ValueError(f"unknown condDensity unit {unit!r}")


def voltage_mv(s):
    val, unit = parse_num_unit(s)
    if unit in ("", "mV"):
        return val
    if unit == "V":
        return val * 1e3
    raise ValueError(f"unknown voltage unit {unit!r}")


def time_ms(s):
    val, unit = parse_num_unit(s)
    if unit in ("", "ms"):
        return val
    if unit == "s":
        return val * 1e3
    raise ValueError(f"unknown time unit {unit!r}")


def conc_mm(s):
    val, unit = parse_num_unit(s)
    if unit in ("", "mM"):
        return val
    raise ValueError(f"unknown concentration unit {unit!r}")


def resistivity_ohm_cm(s):
    val, unit = parse_num_unit(s)
    if unit in ("", "ohm_cm"):
        return val
    if unit == "kohm_cm":
        return val * 1e3
    raise ValueError(f"unknown resistivity unit {unit!r}")


class Segment:
    __slots__ = ("id", "parent", "prox", "distal", "diam")

    def __init__(self, sid, parent, prox, distal, diam):
        self.id = sid
        self.parent = parent  # None for root
        self.prox = prox      # (x, y, z) or None
        self.distal = distal  # (x, y, z)
        self.diam = diam      # (prox_diam, distal_diam)


class Group:
    def __init__(self, gid):
        self.id = gid
        self.members = []   # segment ids
        self.includes = []  # group ids


class Density:
    """One channel density element (uniform or non-uniform)."""
    def __init__(self, el):
        self.ion = attr(el, "ionChannel")
        self.erev = voltage_mv(attr(el, "erev", "0mV")) if attr(el, "erev") else None
        self.ion_name = attr(el, "ion")
        self.ghk = local(el.tag) in ("channelDensityGHK2", "channelDensityGHK2NonUniform")
        self.variable_params = []  # (segment_group, density_or_None, inhom_expr_or_None)
        self.segment_group = attr(el, "segmentGroup")
        cd = attr(el, "condDensity")
        self.cond_density = cond_to_s_per_cm2(cd) if cd else None
        for vp in el:
            if local(vp.tag) != "variableParameter":
                continue
            sg = attr(vp, "segmentGroup")
            proximal = distal = None
            inhom = None
            for sub in vp:
                t = local(sub.tag)
                if t == "proximal":
                    proximal = cond_to_s_per_cm2(attr(sub, "value"))
                elif t == "distal":
                    distal = cond_to_s_per_cm2(attr(sub, "value"))
                elif t == "inhomogeneousValue":
                    inhom = attr(sub, "value")
            if inhom is not None:
                self.variable_params.append((sg, None, inhom))
            else:
                self.variable_params.append((sg, (proximal, distal), None))


def parse_cell(path):
    tree = ET.parse(path)
    root = tree.getroot()
    segments = {}
    groups = {}
    densities = []
    species = []
    ra = 100.0
    cm = 1.0
    first_leak = None
    leak_rev = -70.0

    for el in root.iter():
        t = local(el.tag)
        if t == "segment":
            sid = int(attr(el, "id"))
            prox = distal = None
            parent = None
            for sub in el:
                st = local(sub.tag)
                if st == "proximal":
                    prox = (float(attr(sub, "x")), float(attr(sub, "y")),
                            float(attr(sub, "z")), float(attr(sub, "diameter")))
                elif st == "distal":
                    distal = (float(attr(sub, "x")), float(attr(sub, "y")),
                              float(attr(sub, "z")), float(attr(sub, "diameter")))
                elif st == "parent":
                    parent = int(attr(sub, "segment"))
            segments[sid] = Segment(sid, parent, prox, distal, distal)
        elif t == "segmentGroup":
            g = Group(attr(el, "id"))
            for sub in el:
                st = local(sub.tag)
                if st == "member":
                    g.members.append(int(attr(sub, "segment")))
                elif st == "include":
                    g.includes.append(attr(sub, "segmentGroup"))
            groups[g.id] = g
        elif t in ("channelDensity", "channelDensityNonUniform",
                   "channelDensityGHK2", "channelDensityGHK2NonUniform"):
            d = Density(el)
            # passive leak detection (ion non_specific / channel pas|leak)
            ion_name = (d.ion_name or "").lower()
            ch = (d.ion or "").lower()
            if ion_name in ("non_specific", "pas", "leak") or ch in ("pas", "leak"):
                if first_leak is None and d.segment_group:
                    first_leak = d.cond_density
                    if d.erev is not None:
                        leak_rev = d.erev
                continue  # leak handled separately (per-group, below)
            densities.append(d)
        elif t == "species":
            species.append({
                "ion": attr(el, "ion"),
                "conc_model": attr(el, "concentrationModel"),
                "segment_group": attr(el, "segmentGroup", "all"),
                "initial": conc_mm(attr(el, "initialConcentration")),
                "initial_ext": conc_mm(attr(el, "initialExtConcentration")),
            })
        elif t == "resistivity":
            ra = resistivity_ohm_cm(attr(el, "value"))
        elif t == "specificCapacitance":
            val, unit = parse_num_unit(attr(el, "value"))
            cm = val if unit in ("", "uF_per_cm2") else val * 1e-3 if unit == "F_per_m2" else val

    # Per-group leak densities (the model declares different leak per group).
    leaks = {}
    for el in root.iter():
        if local(el.tag) != "channelDensity":
            continue
        d = Density(el)
        ion_name = (d.ion_name or "").lower()
        ch = (d.ion or "").lower()
        if ion_name in ("non_specific", "pas", "leak") or ch in ("pas", "leak"):
            if d.segment_group and d.cond_density is not None:
                leaks.setdefault(d.segment_group, (d.cond_density, d.erev or leak_rev))

    return segments, groups, densities, species, ra, cm, first_leak, leak_rev, leaks


def resolve_group(groups, gid, _stack=None):
    """Resolve a segmentGroup to a set of segment ids (recursive includes)."""
    _stack = _stack or ()
    out = set()
    if gid not in groups:
        return out
    g = groups[gid]
    for m in g.members:
        out.add(m)
    for inc in g.includes:
        if inc in _stack:
            continue
        out |= resolve_group(groups, inc, _stack + (gid,))
    return out


def discretize(segments, ra, cm, rm, d_lambda=D_LAMBDA):
    """Port of discretize.rs: d_λ rule + branch nodes. Returns list of
    compartments: dict(parent, seg_id, length_um, diameter_um, area_um2,
    path_um, branch: bool)."""
    root_id = None
    index = {}
    for sid, s in segments.items():
        index[sid] = s
        if s.parent is None:
            root_id = sid
    assert root_id is not None, "no root segment"

    children = {}
    for sid, s in segments.items():
        if s.parent is not None:
            children.setdefault(s.parent, []).append(sid)

    def dist(p, q):
        return np.sqrt((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 + (p[2] - q[2]) ** 2)

    def geom(s):
        distal = s.distal
        if s.prox is not None:
            prox = s.prox
        elif s.parent is not None:
            prox = segments[s.parent].distal
        else:
            prox = distal
        length = dist(prox, distal)
        diam = (prox[3] + distal[3]) / 2.0
        if diam <= 0:
            raise ValueError(f"segment {s.id} non-positive diameter")
        if length <= 0:
            length = diam
        return length, diam, prox, distal

    def space_constant(d_um, rm_, ra_):
        return np.sqrt(d_um * rm_ / (4.0 * ra_)) * 100.0

    comps = []
    last_comp = {}
    queue = [root_id]
    head = 0
    while head < len(queue):
        seg_id = queue[head]
        head += 1
        s = index[seg_id]
        length, diam, prox, distal = geom(s)
        parent_comp = last_comp[s.parent] if s.parent is not None else None

        lam = space_constant(diam, rm, ra)
        target = d_lambda * lam
        n = max(int(np.ceil(length / target)) if target > 0 else 1, 1)
        comp_len = length / n
        area = np.pi * diam * comp_len
        axis = (distal[0] - prox[0], distal[1] - prox[1], distal[2] - prox[2])

        for j in range(n):
            parent = parent_comp if j == 0 else len(comps) - 1
            f = (j + 0.5) / n
            if parent is None:
                path = comp_len * 0.5
            else:
                pc = comps[parent]
                path = pc["path_um"] + pc["length_um"] * 0.5 + comp_len * 0.5
            comps.append({
                "parent": parent,
                "seg_id": seg_id,
                "length_um": comp_len,
                "diameter_um": diam,
                "area_um2": area,
                "path_um": path,
                "branch": False,
            })
        last_comp[seg_id] = len(comps) - 1

        if len(children.get(seg_id, [])) >= 2:
            bp = len(comps)
            parent_c = comps[last_comp[seg_id]]
            comps.append({
                "parent": last_comp[seg_id],
                "seg_id": seg_id,
                "length_um": 0.0,
                "diameter_um": diam,
                "area_um2": 0.0,
                "path_um": parent_c["path_um"] + parent_c["length_um"] * 0.5,
                "branch": True,
            })
            last_comp[seg_id] = bp

        queue.extend(children.get(seg_id, []))

    return comps


def eval_inhom(expr, p):
    """Tiny evaluator for the inhomogeneousValue expressions: numbers,
    + - * /, parentheses, H(...) Heaviside, exp(...) exponential, and a bare
    path-length symbol. Returns S/cm² (the LEMS expression is in S/m²)."""
    toks = re.findall(r"\d+\.?\d*(?:[eE][+-]?\d+)?|[A-Za-z_][A-Za-z0-9_]*|[+\-*/(),]",
                      expr)
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def expr_():
        nonlocal pos
        v = term()
        while peek() in ("+", "-"):
            op = peek()
            pos += 1
            r = term()
            v = v + r if op == "+" else v - r
        return v

    def term():
        nonlocal pos
        v = factor()
        while peek() in ("*", "/"):
            op = peek()
            pos += 1
            r = factor()
            v = v * r if op == "*" else (v / r if r != 0 else v)
        return v

    def factor():
        nonlocal pos
        t = peek()
        if t is None:
            return 0.0
        if t == "-":
            pos += 1
            return -factor()
        if t == "(":
            pos += 1
            v = expr_()
            if peek() == ")":
                pos += 1
            return v
        if re.match(r"^\d", t):
            pos += 1
            return float(t)
        # identifier
        name = t
        pos += 1
        if peek() == "(":
            pos += 1
            arg = expr_()
            if peek() == ")":
                pos += 1
            if name == "exp":
                return math.exp(arg)
            return 1.0 if arg >= 0.0 else 0.0  # H(x)
        return p  # path-length symbol
    return expr_() * 1e-4  # S/m² → S/cm²


def build_neuron(comps, densities, groups, species, ra, cm, first_leak, leaks,
                 leak_rev=-70.0):
    from neuron import h
    h.load_file("stdrun.hoc")
    h.celsius = 35.0
    h.secondorder = 0
    h.dt = DT

    # ── sections: one per real compartment ──────────────────────────────
    n = len(comps)
    real = [not c["branch"] for c in comps]
    sec_of = [None] * n
    for i, c in enumerate(comps):
        if c["branch"]:
            continue
        sec = h.Section(name=f"c{i}")
        sec.L = c["length_um"]
        sec.diam = c["diameter_um"]
        sec.Ra = ra
        sec.cm = cm
        sec.nseg = 1
        sec_of[i] = sec
    # connections: child(0) -> parent real section (1.0); branch nodes are
    # shared connection points (children attach to the branch's parent at 1.0).
    for i, c in enumerate(comps):
        if c["branch"] or c["parent"] is None:
            continue
        p = c["parent"]
        while comps[p]["branch"]:
            p = comps[p]["parent"]
        sec_of[i].connect(sec_of[p](1.0))

    # ── mechanism lookup helper ─────────────────────────────────────────
    mech_names = {d.ion: d.ion for d in densities}
    for ch in GHK_CHANNELS:
        mech_names.setdefault(ch, ch)

    def comps_of_group(gid):
        seg_ids = resolve_group(groups, gid)
        return [i for i, c in enumerate(comps)
                if not c["branch"] and c["seg_id"] in seg_ids]

    def insert_mech(comp, mech, gbar, erev=None):
        sec = sec_of[comp]
        sec.insert(mech)
        seg = sec(0.5)
        mo = getattr(seg, mech)
        mo.gbar = gbar
        if erev is not None:
            mo.erev = erev

    # Ion concentrations for the GHK channels (cal/cat read cai, cao).
    h.cao0_ca_ion = 2.0
    h.cai0_ca_ion = 1e-4

    # ── channel densities (uniform + non-uniform) ──────────────────────
    for d in densities:
        mech = d.ion
        if not d.variable_params:
            for comp in comps_of_group(d.segment_group):
                insert_mech(comp, mech, d.cond_density, d.erev)
        else:
            for sg, linear, inhom in d.variable_params:
                comps_g = comps_of_group(sg)
                if not comps_g:
                    continue
                paths = [comps[c]["path_um"] for c in comps_g]
                pmin, pmax = min(paths), max(paths)
                span = pmax - pmin
                for comp in comps_g:
                    p = comps[comp]["path_um"]
                    if linear is not None:
                        u = (p - pmin) / span if span > 0 else 0.0
                        u = max(0.0, min(1.0, u))
                        density = linear[0] + (linear[1] - linear[0]) * u
                    else:
                        density = eval_inhom(inhom, p)
                    insert_mech(comp, mech, density, d.erev)

    # ── passive leak ────────────────────────────────────────────────
    # The engine gives every compartment a uniform leak (Rm = 1/first_leak)
    # and then overrides the per-group density where the model declares one.
    # Mirror that exactly: default leak everywhere, per-group override on top.
    leak_assigned = set()
    for gid, (leak_density, erev) in leaks.items():
        for comp in comps_of_group(gid):
            insert_mech(comp, "leak_chan", leak_density, erev)
            leak_assigned.add(comp)
    for i, c in enumerate(comps):
        if c["branch"] or i in leak_assigned:
            continue
        insert_mech(i, "leak_chan", first_leak, leak_rev)

    # ── Ca pools (capool) on the species groups ────────────────────────
    for sp in species:
        if sp["ion"].lower() != "ca":
            continue
        for comp in comps_of_group(sp["segment_group"]):
            sec = sec_of[comp]
            sec.insert("capool")
            seg = sec(0.5)
            seg.capool.depth = CAPOOL_DEPTH_NM
            seg.capool.tau = CAPOOL_TAU_MS
            seg.capool.cai0 = sp["initial"]

    # Keep the section references alive: NEURON sections are garbage-
    # collected when their last Python handle is dropped, so we must return
    # `sec_of` (and the caller must hold it) for the run to see the cell.
    return h, sec_of


def compile_mods():
    tmp = tempfile.mkdtemp(prefix="poirazi_full_mods_")
    for m in MODS:
        src = os.path.join(HERE, f"{m}.mod")
        if not os.path.exists(src):
            raise FileNotFoundError(f"missing {src}")
        shutil.copy(src, os.path.join(tmp, f"{m}.mod"))
    subprocess.run(["cmd.exe", "/c", MKNrndll], cwd=tmp, check=True,
                   capture_output=True)
    return tmp, os.path.join(tmp, "nrnmech.dll")


def main():
    cell_dir = sys.argv[1]
    out_dir = sys.argv[2]
    celsius = float(sys.argv[3])

    cell_file = os.path.join(cell_dir, "poirazi.cell.nml")
    segments, groups, densities, species, ra, cm, first_leak, leak_rev, leaks = \
        parse_cell(cell_file)
    print(f"segments={len(segments)} groups={len(groups)} "
          f"densities={len(densities)} species={len(species)} "
          f"Ra={ra} Cm={cm} first_leak={first_leak} leaks={len(leaks)}")

    # Rm from the first leak (engine convention: CableParams::from_biophysics).
    rm = 1.0 / first_leak if first_leak and first_leak > 0 else 20000.0
    comps = discretize(segments, ra, cm, rm)
    print(f"compartments={len(comps)} root=0")

    tmp, dll = compile_mods()
    print(f"compiled {len(MODS)} mods -> {dll}")

    old_cwd = os.getcwd()
    os.chdir(tempfile.gettempdir())
    from neuron import h
    h.nrn_load_dll(dll)
    h, sec_of = build_neuron(comps, densities, groups, species, ra, cm,
                             first_leak, leaks, leak_rev)

    # The root compartment (soma) is comps[0]; its section is sec_of[0].
    rec_sec = sec_of[0]
    assert rec_sec is not None, "soma section (comps[0]) missing"

    stim = h.IClamp(rec_sec(0.5))

    def run(i_amp, on_ms, off_ms, tstop_ms):
        v_vec = h.Vector()
        v_vec.record(rec_sec(0.5)._ref_v)
        stim.delay = on_ms
        stim.dur = off_ms - on_ms
        stim.amp = i_amp
        h.tstop = tstop_ms
        h.finitialize(V0)
        h.continuerun(tstop_ms)
        return np.array(v_vec)

    for name, i_amp, on_ms, off_ms, tstop in PROTOCOLS:
        v = run(i_amp, on_ms, off_ms, tstop)
        n = len(v)
        spikes = int(np.sum((v[:-1] < THRESH) & (v[1:] >= THRESH)))
        grid = v[:: int(5.0 / DT)]
        print(f"# {name}: I={i_amp:+.1e} nA  n_steps={n}  spikes={spikes}  "
              f"V range: [{v.min():.4f}, {v.max():.4f}] mV")
        const = f"REF_V_{name.upper()}"
        print(f"pub const {const}: [f32; {len(grid)}] = [")
        for i in range(0, len(grid), 8):
            row = ", ".join(f"{x:.4f}" for x in grid[i:i + 8])
            print(f"    {row},")
        print("];")

    os.chdir(old_cwd)


if __name__ == "__main__":
    main()
